-- Attachments (PLAIN.md 11.1 rule 4): every document can keep a photo or scan of its paper, for example the signed
-- delivery note or the supplier's receipt. One per document; bills and expenses keep theirs on their own row.
-- doc_type is the document's API path (goods-receipts, invoices, ...); the file is private (FileStorage "documents").
CREATE TABLE attachments (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT       NOT NULL REFERENCES businesses (id),
    doc_type    VARCHAR(30)  NOT NULL,
    doc_id      BIGINT       NOT NULL,
    path        VARCHAR(255) NOT NULL,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by  BIGINT,
    updated_by  BIGINT,
    UNIQUE (business_id, doc_type, doc_id)
);
