-- Expenses (PLAIN.md 11.9) and stock counts (PLAIN.md 11.2): the two areas the web app needed that V1 did not have.

CREATE TABLE expense_categories (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT       NOT NULL REFERENCES businesses (id),
    name_en     VARCHAR(120) NOT NULL,
    name_km     VARCHAR(120),
    is_active   BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by  BIGINT,
    updated_by  BIGINT
);
CREATE INDEX ix_expense_categories_business ON expense_categories (business_id);

CREATE TABLE expenses (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id   BIGINT        NOT NULL REFERENCES businesses (id),
    number        VARCHAR(30)   NOT NULL,
    branch_id     BIGINT        NOT NULL REFERENCES branches (id),
    category_id   BIGINT        NOT NULL REFERENCES expense_categories (id),
    supplier_id   BIGINT        REFERENCES suppliers (id),
    expense_date  DATE          NOT NULL,
    method        VARCHAR(10)   NOT NULL CHECK (method IN ('CASH', 'KHQR', 'BANK')),
    currency      VARCHAR(3)    NOT NULL CHECK (currency IN ('USD', 'KHR')),
    amount        NUMERIC(16,2) NOT NULL CHECK (amount > 0),
    exchange_rate NUMERIC(12,2) NOT NULL,
    amount_usd    NUMERIC(14,2) NOT NULL,
    reference     VARCHAR(60),
    note          VARCHAR(500),
    status        VARCHAR(10)   NOT NULL CHECK (status IN ('POSTED', 'VOID')),
    voided_at     TIMESTAMPTZ,
    created_at    TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ   NOT NULL DEFAULT now(),
    created_by    BIGINT,
    updated_by    BIGINT,
    UNIQUE (business_id, number)
);
CREATE INDEX ix_expenses_business_date ON expenses (business_id, expense_date);

CREATE TABLE stock_counts (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id  BIGINT       NOT NULL REFERENCES businesses (id),
    number       VARCHAR(30)  NOT NULL,
    branch_id    BIGINT       NOT NULL REFERENCES branches (id),
    warehouse_id BIGINT       NOT NULL REFERENCES warehouses (id),
    category_id  BIGINT       REFERENCES categories (id),
    status       VARCHAR(10)  NOT NULL CHECK (status IN ('DRAFT', 'POSTED', 'VOID')),
    note         VARCHAR(500),
    posted_at    TIMESTAMPTZ,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by   BIGINT,
    updated_by   BIGINT,
    UNIQUE (business_id, number)
);

CREATE TABLE stock_count_items (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT        NOT NULL REFERENCES businesses (id),
    count_id    BIGINT        NOT NULL REFERENCES stock_counts (id),
    product_id  BIGINT        NOT NULL REFERENCES products (id),
    system_qty  NUMERIC(14,3) NOT NULL,
    counted_qty NUMERIC(14,3),
    unit_cost   NUMERIC(14,4) NOT NULL DEFAULT 0
);
CREATE INDEX ix_stock_count_items_count ON stock_count_items (count_id);
