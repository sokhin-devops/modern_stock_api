-- Reorder level per branch (FR-4.7, PLAIN.md 11.11): a branch may keep its own level; without one it uses the product's.
-- 0 means the product is not watched in that branch.

CREATE TABLE branch_reorder_levels (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id   BIGINT        NOT NULL REFERENCES businesses (id),
    branch_id     BIGINT        NOT NULL REFERENCES branches (id),
    product_id    BIGINT        NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    reorder_level NUMERIC(14,3) NOT NULL CHECK (reorder_level >= 0),
    created_at    TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ   NOT NULL DEFAULT now(),
    created_by    BIGINT,
    updated_by    BIGINT,
    UNIQUE (branch_id, product_id)
);
CREATE INDEX branch_reorder_levels_product ON branch_reorder_levels (product_id);
