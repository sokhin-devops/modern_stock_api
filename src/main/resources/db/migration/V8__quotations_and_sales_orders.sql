-- Quotations and sales orders (FR-3.10, FR-3.11, PLAIN.md 11.8): Quotation -> Sales order -> Delivery -> Invoice.
-- A quotation is a price offer valid until a date; accepted, it becomes a sales order with the same prices. An order is
-- delivered in one or more deliveries, and each delivery makes its invoice.

CREATE TABLE quotations (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id    BIGINT        NOT NULL REFERENCES businesses (id),
    number         VARCHAR(30)   NOT NULL,
    branch_id      BIGINT        NOT NULL REFERENCES branches (id),
    customer_id    BIGINT        NOT NULL REFERENCES customers (id),
    quote_date     DATE          NOT NULL,
    valid_until    DATE          NOT NULL,
    exchange_rate  NUMERIC(10,2) NOT NULL,
    subtotal       NUMERIC(14,2) NOT NULL,
    -- the discount on the whole document; discount = line discounts + order_discount
    order_discount NUMERIC(14,2) NOT NULL DEFAULT 0,
    discount       NUMERIC(14,2) NOT NULL DEFAULT 0,
    vat            NUMERIC(14,2) NOT NULL DEFAULT 0,
    total          NUMERIC(14,2) NOT NULL,
    status         VARCHAR(10)   NOT NULL CHECK (status IN ('DRAFT', 'SENT', 'ACCEPTED', 'DECLINED', 'EXPIRED')),
    sales_order_id BIGINT,
    note           VARCHAR(500),
    created_at     TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ   NOT NULL DEFAULT now(),
    created_by     BIGINT,
    updated_by     BIGINT,
    UNIQUE (business_id, number)
);
CREATE INDEX quotations_customer ON quotations (business_id, customer_id, status);

CREATE TABLE quotation_items (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id  BIGINT        NOT NULL REFERENCES businesses (id),
    quotation_id BIGINT        NOT NULL REFERENCES quotations (id) ON DELETE CASCADE,
    product_id   BIGINT        NOT NULL REFERENCES products (id),
    unit_id      BIGINT        NOT NULL REFERENCES units (id),
    qty          NUMERIC(14,3) NOT NULL CHECK (qty > 0),
    unit_price   NUMERIC(14,2) NOT NULL,
    discount     NUMERIC(14,2) NOT NULL DEFAULT 0
);

CREATE TABLE sales_orders (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id    BIGINT        NOT NULL REFERENCES businesses (id),
    number         VARCHAR(30)   NOT NULL,
    branch_id      BIGINT        NOT NULL REFERENCES branches (id),
    warehouse_id   BIGINT        NOT NULL REFERENCES warehouses (id),
    customer_id    BIGINT        NOT NULL REFERENCES customers (id),
    quotation_id   BIGINT REFERENCES quotations (id),
    order_date     DATE          NOT NULL,
    delivery_date  DATE,
    exchange_rate  NUMERIC(10,2) NOT NULL,
    subtotal       NUMERIC(14,2) NOT NULL,
    order_discount NUMERIC(14,2) NOT NULL DEFAULT 0,
    discount       NUMERIC(14,2) NOT NULL DEFAULT 0,
    vat            NUMERIC(14,2) NOT NULL DEFAULT 0,
    total          NUMERIC(14,2) NOT NULL,
    status         VARCHAR(20)   NOT NULL CHECK (status IN ('CONFIRMED', 'PARTIALLY_DELIVERED', 'DELIVERED', 'CLOSED', 'CANCELLED')),
    note           VARCHAR(500),
    created_at     TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ   NOT NULL DEFAULT now(),
    created_by     BIGINT,
    updated_by     BIGINT,
    UNIQUE (business_id, number)
);
CREATE INDEX sales_orders_customer ON sales_orders (business_id, customer_id, status);

CREATE TABLE sales_order_items (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id    BIGINT        NOT NULL REFERENCES businesses (id),
    sales_order_id BIGINT        NOT NULL REFERENCES sales_orders (id) ON DELETE CASCADE,
    product_id     BIGINT        NOT NULL REFERENCES products (id),
    unit_id        BIGINT        NOT NULL REFERENCES units (id),
    qty_ordered    NUMERIC(14,3) NOT NULL CHECK (qty_ordered > 0),
    qty_delivered  NUMERIC(14,3) NOT NULL DEFAULT 0,
    unit_price     NUMERIC(14,2) NOT NULL,
    -- the line discount for the whole ordered quantity; a delivery takes its share
    discount       NUMERIC(14,2) NOT NULL DEFAULT 0
);

ALTER TABLE quotations ADD CONSTRAINT quotations_sales_order_fk FOREIGN KEY (sales_order_id) REFERENCES sales_orders (id);

-- A delivery may fill a sales order; its lines say which order line they fill
ALTER TABLE deliveries ADD COLUMN sales_order_id BIGINT REFERENCES sales_orders (id);
CREATE INDEX deliveries_sales_order ON deliveries (business_id, sales_order_id);
ALTER TABLE sale_items ADD COLUMN sales_order_item_id BIGINT REFERENCES sales_order_items (id);
