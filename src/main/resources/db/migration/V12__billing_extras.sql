-- A business's add-ons: Pending until its first invoice is paid, then Active; removing one ends it with the period.
CREATE TABLE subscription_addons (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id          BIGINT      NOT NULL REFERENCES businesses (id),
    addon_id             BIGINT      NOT NULL REFERENCES addons (id),
    quantity             INT         NOT NULL DEFAULT 1 CHECK (quantity > 0),
    status               VARCHAR(10) NOT NULL CHECK (status IN ('PENDING', 'ACTIVE', 'ENDED')),
    remove_at_period_end BOOLEAN     NOT NULL DEFAULT FALSE,
    started_at           TIMESTAMPTZ,
    ended_at             TIMESTAMPTZ,
    created_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by           BIGINT,
    updated_by           BIGINT
);
CREATE INDEX subscription_addons_business ON subscription_addons (business_id, status);

ALTER TABLE billing_invoices DROP CONSTRAINT billing_invoices_kind_check;
ALTER TABLE billing_invoices ADD CONSTRAINT billing_invoices_kind_check CHECK (kind IN ('NEW', 'RENEWAL', 'UPGRADE', 'ADDON'));
ALTER TABLE billing_invoices ADD COLUMN billing_cycle VARCHAR(10) NOT NULL DEFAULT 'MONTHLY' CHECK (billing_cycle IN ('MONTHLY', 'YEARLY'));
ALTER TABLE billing_invoices ADD COLUMN subscription_addon_id BIGINT REFERENCES subscription_addons (id);
-- what the amount is for, e.g. "Pro, yearly + Extra branch" or "Pro − Basic, 18 days"
ALTER TABLE billing_invoices ADD COLUMN description VARCHAR(255);

-- A monthly plan can switch to yearly (or back) at the end of the period.
ALTER TABLE subscriptions ADD COLUMN pending_billing_cycle VARCHAR(10) CHECK (pending_billing_cycle IN ('MONTHLY', 'YEARLY'));

-- A bank transfer: the Owner's screenshot waits for the super admin.
ALTER TABLE billing_payments ADD COLUMN bank VARCHAR(20);
ALTER TABLE billing_payments ADD COLUMN proof_path VARCHAR(255);
ALTER TABLE billing_payments ADD COLUMN reviewed_by BIGINT;

-- Reminders already sent: 7, 3 and 1 days before a renewal or the end of a trial.
CREATE TABLE billing_reminders (
    business_id BIGINT      NOT NULL REFERENCES businesses (id),
    due_at      TIMESTAMPTZ NOT NULL,
    days_before INT         NOT NULL,
    sent_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (business_id, due_at, days_before)
);

