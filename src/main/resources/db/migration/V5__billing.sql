-- Billing (PLAIN.md 11.13): the platform's own invoices to a business (SUB-…, in USD) and the payments for them, separate
-- from the shop's sales invoices. Nothing here is per tenant: the super admin sees every business.

CREATE SEQUENCE billing_invoice_number_seq;

CREATE TABLE billing_invoices (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id  BIGINT        NOT NULL REFERENCES businesses (id),
    number       VARCHAR(30)   NOT NULL UNIQUE,
    kind         VARCHAR(10)   NOT NULL CHECK (kind IN ('NEW', 'RENEWAL', 'UPGRADE')),
    plan_id      BIGINT        NOT NULL REFERENCES plans (id),
    period_start TIMESTAMPTZ   NOT NULL,
    period_end   TIMESTAMPTZ   NOT NULL,
    amount       NUMERIC(14,2) NOT NULL CHECK (amount >= 0),
    status       VARCHAR(8)    NOT NULL CHECK (status IN ('OPEN', 'PAID', 'VOID')),
    paid_at      TIMESTAMPTZ,
    created_at   TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ   NOT NULL DEFAULT now(),
    created_by   BIGINT,
    updated_by   BIGINT
);
CREATE INDEX billing_invoices_business ON billing_invoices (business_id, created_at DESC);

CREATE TABLE billing_payments (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id    BIGINT        NOT NULL REFERENCES businesses (id),
    invoice_id     BIGINT        NOT NULL REFERENCES billing_invoices (id),
    gateway        VARCHAR(20)   NOT NULL,
    reference      VARCHAR(60)   NOT NULL UNIQUE,
    amount         NUMERIC(14,2) NOT NULL,
    status         VARCHAR(10)   NOT NULL CHECK (status IN ('PENDING', 'SUCCEEDED', 'FAILED')),
    failure_reason VARCHAR(255),
    completed_at   TIMESTAMPTZ,
    created_at     TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ   NOT NULL DEFAULT now(),
    created_by     BIGINT,
    updated_by     BIGINT
);
CREATE INDEX billing_payments_invoice ON billing_payments (invoice_id);

-- The Owner chose a paid plan (during the trial: billed when the trial ends), and since when a renewal is unpaid.
ALTER TABLE subscriptions ADD COLUMN subscribed     BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE subscriptions ADD COLUMN past_due_since TIMESTAMPTZ;

-- When a plan ends, extras above the Free limits are switched off, not deleted (PLAIN.md 11.13 rule 3): a read-only
-- branch takes no new work, and members disabled by the plan come back when the business subscribes again.
ALTER TABLE branches ADD COLUMN read_only BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE business_members ADD COLUMN disabled_by_plan BOOLEAN NOT NULL DEFAULT FALSE;
