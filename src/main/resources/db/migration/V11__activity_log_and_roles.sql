-- Activity log (FR-6.22, PLAIN.md activity_logs): who did what and when, with the old and new values of what changed.
-- Entries of one branch carry its ID, so a Manager sees their own branch; business-wide ones (settings, roles) have none.

CREATE TABLE activity_logs (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT       NOT NULL REFERENCES businesses (id),
    branch_id   BIGINT       REFERENCES branches (id),
    user_id     BIGINT       REFERENCES users (id),
    action      VARCHAR(40)  NOT NULL,
    entity_type VARCHAR(30)  NOT NULL,
    entity_id   BIGINT,
    -- what the entry is about, as it was named then (a product name, a document number)
    label       VARCHAR(200),
    old_values  JSONB,
    new_values  JSONB,
    ip_address  VARCHAR(45),
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX activity_logs_business ON activity_logs (business_id, id DESC);

INSERT INTO permissions (code, area, name_en) VALUES ('activity:view', 'Business', 'Activity log');
INSERT INTO role_permissions (role_id, permission_id)
SELECT r.id, p.id FROM roles r JOIN permissions p ON p.code = 'activity:view'
WHERE r.code IN ('OWNER', 'MANAGER') AND r.business_id IS NULL;

-- Custom roles (FR-6.24): a business's own roles carry its ID; the code is generated, the names are the Owner's.
CREATE UNIQUE INDEX ux_roles_business_code ON roles (COALESCE(business_id, 0), code);

-- Members in several branches (FR-6.18): business_members.branch_id is the member's first branch (empty = all
-- branches); the other branches they work in are listed here.
CREATE TABLE member_branches (
    member_id BIGINT NOT NULL REFERENCES business_members (id) ON DELETE CASCADE,
    branch_id BIGINT NOT NULL REFERENCES branches (id),
    PRIMARY KEY (member_id, branch_id)
);
