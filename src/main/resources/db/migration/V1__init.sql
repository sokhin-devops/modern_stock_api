    to_id       BIGINT        NOT NULL,
    amount      NUMERIC(14,2) NOT NULL CHECK (amount > 0),
    created_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),
    created_by  BIGINT,
    updated_by  BIGINT
);
CREATE INDEX ix_allocations_from ON allocations (business_id, from_type, from_id);
CREATE INDEX ix_allocations_to ON allocations (business_id, to_type, to_id);
