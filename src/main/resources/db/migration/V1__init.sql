    exchange_rate NUMERIC(10,2) NOT NULL,
    amount_usd    NUMERIC(14,2) NOT NULL,
    reference     VARCHAR(60),
    cash_shift_id BIGINT REFERENCES cash_shifts (id),
    paid_at       TIMESTAMPTZ   NOT NULL,
    status        VARCHAR(10)   NOT NULL CHECK (status IN ('POSTED', 'VOID')),
    note          VARCHAR(500),
    created_at    TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ   NOT NULL DEFAULT now(),
    created_by    BIGINT,
    updated_by    BIGINT,
    UNIQUE (business_id, number)
);
CREATE INDEX ix_payments_party ON payments (business_id, party_type, party_id);

