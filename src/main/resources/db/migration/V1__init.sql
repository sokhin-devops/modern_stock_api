-- ModernStock schema, part 1: accounts, businesses, catalog, stock, purchases, sales and money.
-- Rules (PLAIN.md 10.3): money NUMERIC(14,2) USD / NUMERIC(14,0) KHR, quantities NUMERIC(14,3) in the base unit,
-- TIMESTAMPTZ for times, business_id on every tenant table, statuses as VARCHAR + CHECK.

-- ---------------------------------------------------------------- platform

CREATE TABLE users (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name              VARCHAR(120) NOT NULL,
    username               VARCHAR(60),
    email                  VARCHAR(160),
    phone                  VARCHAR(20),
    password_hash          VARCHAR(100) NOT NULL,
    locale                 VARCHAR(5)   NOT NULL DEFAULT 'km',
    ui_mode                VARCHAR(10)  NOT NULL DEFAULT 'system',
    ui_density             VARCHAR(12)  NOT NULL DEFAULT 'comfortable',
    status                 VARCHAR(12)  NOT NULL CHECK (status IN ('UNVERIFIED', 'ACTIVE', 'DISABLED')),
    email_verified_at      TIMESTAMPTZ,
    managed_by_business_id BIGINT,
    is_super_admin         BOOLEAN      NOT NULL DEFAULT FALSE,
    last_login_at          TIMESTAMPTZ,
    created_at             TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at             TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by             BIGINT,
    updated_by             BIGINT
);
CREATE UNIQUE INDEX ux_users_email ON users (lower(email));
CREATE UNIQUE INDEX ux_users_username ON users (lower(username));

CREATE TABLE businesses (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name_en              VARCHAR(120) NOT NULL,
    name_km              VARCHAR(120),
    business_type        VARCHAR(30)  NOT NULL,
    phone                VARCHAR(20),
    email                VARCHAR(160),
    address              VARCHAR(255),
    province             VARCHAR(60),
    vat_tin              VARCHAR(30),
    logo_path            VARCHAR(255),
    theme_color          VARCHAR(20),
    language             VARCHAR(5)   NOT NULL DEFAULT 'km',
    status               VARCHAR(12)  NOT NULL CHECK (status IN ('SETTING_UP', 'ACTIVE', 'SUSPENDED', 'ARCHIVED')),
    onboarding_completed BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at           TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at           TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by           BIGINT,
    updated_by           BIGINT
);

CREATE TABLE permissions (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code    VARCHAR(60)  NOT NULL UNIQUE,
    area    VARCHAR(30)  NOT NULL,
    name_en VARCHAR(120) NOT NULL,
    name_km VARCHAR(120)
);

CREATE TABLE roles (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT REFERENCES businesses (id),
    code        VARCHAR(30)  NOT NULL,
    name_en     VARCHAR(60)  NOT NULL,
    name_km     VARCHAR(60),
    is_built_in BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by  BIGINT,
    updated_by  BIGINT
);
CREATE UNIQUE INDEX ux_roles_business_name ON roles (COALESCE(business_id, 0), name_en);

CREATE TABLE role_permissions (
    role_id       BIGINT NOT NULL REFERENCES roles (id) ON DELETE CASCADE,
    permission_id BIGINT NOT NULL REFERENCES permissions (id),
    PRIMARY KEY (role_id, permission_id)
);

CREATE TABLE refresh_tokens (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL REFERENCES users (id),
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    expires_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by BIGINT,
    updated_by BIGINT
);
CREATE INDEX ix_refresh_tokens_user ON refresh_tokens (user_id);

CREATE TABLE user_tokens (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL REFERENCES users (id),
    type       VARCHAR(20) NOT NULL CHECK (type IN ('VERIFY_EMAIL', 'PASSWORD_RESET')),
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    expires_at TIMESTAMPTZ NOT NULL,
    used_at    TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by BIGINT,
    updated_by BIGINT
);

CREATE TABLE platform_settings (
    key   VARCHAR(60) PRIMARY KEY,
    value VARCHAR(255) NOT NULL
);

CREATE TABLE contact_messages (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(120) NOT NULL,
    phone      VARCHAR(20),
    email      VARCHAR(160),
    message    TEXT         NOT NULL,
    language   VARCHAR(5)   NOT NULL DEFAULT 'km',
    status     VARCHAR(10)  NOT NULL CHECK (status IN ('NEW', 'READ', 'DONE')),
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by BIGINT,
    updated_by BIGINT
);

-- ---------------------------------------------------------------- billing (platform tables with business_id)

CREATE TABLE plans (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code          VARCHAR(20)   NOT NULL UNIQUE,
    name          VARCHAR(60)   NOT NULL,
    price_monthly NUMERIC(14,2) NOT NULL,
    price_yearly  NUMERIC(14,2),
    is_public     BOOLEAN       NOT NULL DEFAULT TRUE,
    sort_order    INT           NOT NULL DEFAULT 0
);

CREATE TABLE plan_limits (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id   BIGINT      NOT NULL REFERENCES plans (id) ON DELETE CASCADE,
    limit_key VARCHAR(30) NOT NULL,
    value     INT,
    UNIQUE (plan_id, limit_key)
);

CREATE TABLE subscriptions (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id          BIGINT      NOT NULL UNIQUE REFERENCES businesses (id),
    plan_id              BIGINT      NOT NULL REFERENCES plans (id),
    status               VARCHAR(12) NOT NULL CHECK (status IN ('TRIALING', 'ACTIVE', 'PAST_DUE', 'EXPIRED', 'CANCELLED')),
    billing_cycle        VARCHAR(10) NOT NULL DEFAULT 'MONTHLY' CHECK (billing_cycle IN ('MONTHLY', 'YEARLY')),
    current_period_start TIMESTAMPTZ,
    current_period_end   TIMESTAMPTZ,
    trial_ends_at        TIMESTAMPTZ,
    cancel_at_period_end BOOLEAN     NOT NULL DEFAULT FALSE,
    pending_plan_id      BIGINT REFERENCES plans (id),
    created_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by           BIGINT,
    updated_by           BIGINT
);

-- ---------------------------------------------------------------- business setup

CREATE TABLE branches (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT       NOT NULL REFERENCES businesses (id),
    code        VARCHAR(20)  NOT NULL,
    name_en     VARCHAR(120) NOT NULL,
    name_km     VARCHAR(120),
    address     VARCHAR(255),
    phone       VARCHAR(20),
    province    VARCHAR(60),
    is_main     BOOLEAN      NOT NULL DEFAULT FALSE,
    is_active   BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by  BIGINT,
    updated_by  BIGINT,
    UNIQUE (business_id, code)
);
CREATE INDEX ix_branches_business ON branches (business_id);

CREATE TABLE warehouses (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id  BIGINT       NOT NULL REFERENCES businesses (id),
    branch_id    BIGINT       NOT NULL REFERENCES branches (id),
    name_en      VARCHAR(120) NOT NULL,
    name_km      VARCHAR(120),
    is_sales     BOOLEAN      NOT NULL DEFAULT FALSE,
    is_receiving BOOLEAN      NOT NULL DEFAULT FALSE,
    is_active    BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by   BIGINT,
    updated_by   BIGINT
);
CREATE INDEX ix_warehouses_business ON warehouses (business_id, branch_id);

CREATE TABLE business_members (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT      NOT NULL REFERENCES businesses (id),
    user_id     BIGINT      NOT NULL REFERENCES users (id),
    role_id     BIGINT      NOT NULL REFERENCES roles (id),
    branch_id   BIGINT REFERENCES branches (id),
    status      VARCHAR(10) NOT NULL CHECK (status IN ('ACTIVE', 'DISABLED', 'REMOVED')),
    invited_by  BIGINT,
    joined_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by  BIGINT,
    updated_by  BIGINT,
    UNIQUE (business_id, user_id)
);
CREATE INDEX ix_business_members_user ON business_members (user_id);

CREATE TABLE invitations (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT      NOT NULL REFERENCES businesses (id),
    role_id     BIGINT      NOT NULL REFERENCES roles (id),
    branch_id   BIGINT REFERENCES branches (id),
    email       VARCHAR(160),
    method      VARCHAR(10) NOT NULL CHECK (method IN ('LINK', 'EMAIL')),
    token_hash  VARCHAR(64) NOT NULL UNIQUE,
    status      VARCHAR(10) NOT NULL CHECK (status IN ('PENDING', 'ACCEPTED', 'DECLINED', 'EXPIRED', 'CANCELLED')),
    expires_at  TIMESTAMPTZ NOT NULL,
    invited_by  BIGINT,
    accepted_by BIGINT,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by  BIGINT,
    updated_by  BIGINT
);
CREATE INDEX ix_invitations_business ON invitations (business_id, status);

CREATE TABLE business_settings (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT       NOT NULL REFERENCES businesses (id),
    key         VARCHAR(60)  NOT NULL,
    value       VARCHAR(255) NOT NULL,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by  BIGINT,
    updated_by  BIGINT,
    UNIQUE (business_id, key)
);

CREATE TABLE exchange_rates (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT        NOT NULL REFERENCES businesses (id),
    rate_date   DATE          NOT NULL,
    usd_to_khr  NUMERIC(10,2) NOT NULL CHECK (usd_to_khr > 0),
    source      VARCHAR(20)   NOT NULL DEFAULT 'MANUAL',
    created_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),
    created_by  BIGINT,
    updated_by  BIGINT,
    UNIQUE (business_id, rate_date)
);

CREATE TABLE document_sequences (
    business_id BIGINT      NOT NULL REFERENCES businesses (id),
    doc_type    VARCHAR(10) NOT NULL,
    period      VARCHAR(6)  NOT NULL,
    last_number INT         NOT NULL,
    PRIMARY KEY (business_id, doc_type, period)
);

-- ---------------------------------------------------------------- catalog and contacts

CREATE TABLE categories (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT       NOT NULL REFERENCES businesses (id),
    parent_id   BIGINT REFERENCES categories (id),
    name_en     VARCHAR(120) NOT NULL,
    name_km     VARCHAR(120),
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by  BIGINT,
    updated_by  BIGINT
);
CREATE INDEX ix_categories_business ON categories (business_id);

CREATE TABLE units (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT      NOT NULL REFERENCES businesses (id),
    name_en     VARCHAR(60) NOT NULL,
    name_km     VARCHAR(60),
    symbol      VARCHAR(10) NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by  BIGINT,
    updated_by  BIGINT
);
CREATE INDEX ix_units_business ON units (business_id);

CREATE TABLE products (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id    BIGINT        NOT NULL REFERENCES businesses (id),
    sku            VARCHAR(40)   NOT NULL,
    barcode        VARCHAR(40),
    name_en        VARCHAR(160)  NOT NULL,
    name_km        VARCHAR(160),
    category_id    BIGINT REFERENCES categories (id),
    base_unit_id   BIGINT        NOT NULL REFERENCES units (id),
    avg_cost       NUMERIC(14,4) NOT NULL DEFAULT 0,
    sell_price     NUMERIC(14,2) NOT NULL DEFAULT 0,
    reorder_level  NUMERIC(14,3) NOT NULL DEFAULT 0,
    lead_time_days INT           NOT NULL DEFAULT 0,
    track_expiry   BOOLEAN       NOT NULL DEFAULT FALSE,
    vat_exempt     BOOLEAN       NOT NULL DEFAULT FALSE,
    image_path     VARCHAR(255),
    is_active      BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at     TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ   NOT NULL DEFAULT now(),
    created_by     BIGINT,
    updated_by     BIGINT,
    UNIQUE (business_id, sku)
);
CREATE UNIQUE INDEX ux_products_barcode ON products (business_id, barcode) WHERE barcode IS NOT NULL;

CREATE TABLE product_units (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT        NOT NULL REFERENCES businesses (id),
    product_id  BIGINT        NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    unit_id     BIGINT        NOT NULL REFERENCES units (id),
    factor      NUMERIC(14,3) NOT NULL CHECK (factor > 0),
    barcode     VARCHAR(40),
    sell_price  NUMERIC(14,2),
    created_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),
    created_by  BIGINT,
    updated_by  BIGINT,
    UNIQUE (product_id, unit_id)
);

CREATE TABLE branch_prices (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT        NOT NULL REFERENCES businesses (id),
    branch_id   BIGINT        NOT NULL REFERENCES branches (id),
    product_id  BIGINT        NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    unit_id     BIGINT        NOT NULL REFERENCES units (id),
    sell_price  NUMERIC(14,2) NOT NULL,
    created_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),
    created_by  BIGINT,
    updated_by  BIGINT,
    UNIQUE (branch_id, product_id, unit_id)
);

CREATE TABLE suppliers (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id          BIGINT        NOT NULL REFERENCES businesses (id),
    name                 VARCHAR(160)  NOT NULL,
    contact_person       VARCHAR(120),
    phone                VARCHAR(20),
    telegram             VARCHAR(60),
    address              VARCHAR(255),
    vat_tin              VARCHAR(30),
    payment_terms_days   INT           NOT NULL DEFAULT 0,
    opening_balance      NUMERIC(14,2) NOT NULL DEFAULT 0,
    opening_balance_date DATE,
    is_active            BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at           TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at           TIMESTAMPTZ   NOT NULL DEFAULT now(),
    created_by           BIGINT,
    updated_by           BIGINT
);
CREATE INDEX ix_suppliers_business ON suppliers (business_id);

CREATE TABLE customers (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id          BIGINT        NOT NULL REFERENCES businesses (id),
    name                 VARCHAR(160)  NOT NULL,
    type                 VARCHAR(12)   NOT NULL DEFAULT 'INDIVIDUAL' CHECK (type IN ('INDIVIDUAL', 'COMPANY')),
    phone                VARCHAR(20),
    address              VARCHAR(255),
    vat_tin              VARCHAR(30),
    credit_limit         NUMERIC(14,2) NOT NULL DEFAULT 0,
    payment_terms_days   INT           NOT NULL DEFAULT 0,
    opening_balance      NUMERIC(14,2) NOT NULL DEFAULT 0,
    opening_balance_date DATE,
    is_active            BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at           TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at           TIMESTAMPTZ   NOT NULL DEFAULT now(),
    created_by           BIGINT,
    updated_by           BIGINT
);
CREATE INDEX ix_customers_business ON customers (business_id, phone);

-- ---------------------------------------------------------------- stock

CREATE TABLE stock_levels (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id  BIGINT        NOT NULL REFERENCES businesses (id),
    warehouse_id BIGINT        NOT NULL REFERENCES warehouses (id),
    product_id   BIGINT        NOT NULL REFERENCES products (id),
    qty_on_hand  NUMERIC(14,3) NOT NULL DEFAULT 0,
    created_at   TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ   NOT NULL DEFAULT now(),
    created_by   BIGINT,
    updated_by   BIGINT,
    UNIQUE (warehouse_id, product_id)
);
CREATE INDEX ix_stock_levels_business ON stock_levels (business_id, product_id);

CREATE TABLE stock_batches (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id  BIGINT        NOT NULL REFERENCES businesses (id),
    product_id   BIGINT        NOT NULL REFERENCES products (id),
    warehouse_id BIGINT        NOT NULL REFERENCES warehouses (id),
    batch_no     VARCHAR(40),
    expiry_date  DATE,
    qty_on_hand  NUMERIC(14,3) NOT NULL DEFAULT 0,
    unit_cost    NUMERIC(14,4) NOT NULL DEFAULT 0,
    received_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),
    created_at   TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ   NOT NULL DEFAULT now(),
    created_by   BIGINT,
    updated_by   BIGINT
);
CREATE INDEX ix_stock_batches_pick ON stock_batches (business_id, product_id, warehouse_id, expiry_date);
CREATE INDEX ix_stock_batches_expiry ON stock_batches (business_id, expiry_date);

CREATE TABLE stock_movements (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id    BIGINT        NOT NULL REFERENCES businesses (id),
    product_id     BIGINT        NOT NULL REFERENCES products (id),
    warehouse_id   BIGINT        NOT NULL REFERENCES warehouses (id),
    batch_id       BIGINT REFERENCES stock_batches (id),
    type           VARCHAR(20)   NOT NULL CHECK (type IN ('OPENING', 'GOODS_RECEIPT', 'PURCHASE_RETURN', 'DELIVERY',
                                                          'SALES_RECEIPT', 'SALES_RETURN', 'TRANSFER_OUT', 'TRANSFER_IN',
                                                          'TRANSFER_RETURN', 'ADJUSTMENT', 'COUNT_ADJUST')),
    qty            NUMERIC(14,3) NOT NULL,
    unit_cost      NUMERIC(14,4) NOT NULL,
    balance_after  NUMERIC(14,3) NOT NULL,
    reference_type VARCHAR(30)   NOT NULL,
    reference_id   BIGINT        NOT NULL,
    user_id        BIGINT,
    created_at     TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ   NOT NULL DEFAULT now(),
    created_by     BIGINT,
    updated_by     BIGINT
);
CREATE INDEX ix_stock_movements_card ON stock_movements (business_id, product_id, warehouse_id, created_at);

CREATE TABLE stock_adjustments (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id  BIGINT       NOT NULL REFERENCES businesses (id),
    number       VARCHAR(30)  NOT NULL,
    branch_id    BIGINT       NOT NULL REFERENCES branches (id),
    warehouse_id BIGINT       NOT NULL REFERENCES warehouses (id),
    kind         VARCHAR(12)  NOT NULL CHECK (kind IN ('OPENING', 'ADJUSTMENT')),
    reason       VARCHAR(20)  NOT NULL CHECK (reason IN ('OPENING', 'DAMAGED', 'EXPIRED', 'LOST', 'OWN_USE', 'FOUND',
                                                         'LOST_IN_TRANSIT', 'CORRECTION', 'OTHER')),
    status       VARCHAR(20)  NOT NULL CHECK (status IN ('DRAFT', 'WAITING_APPROVAL', 'POSTED', 'REJECTED', 'VOID')),
    approved_by  BIGINT,
    posted_at    TIMESTAMPTZ,
    voided_at    TIMESTAMPTZ,
    voided_by    BIGINT,
    note         VARCHAR(500),
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by   BIGINT,
    updated_by   BIGINT,
    UNIQUE (business_id, number)
);

CREATE TABLE stock_adjustment_items (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id   BIGINT        NOT NULL REFERENCES businesses (id),
    adjustment_id BIGINT        NOT NULL REFERENCES stock_adjustments (id) ON DELETE CASCADE,
    product_id    BIGINT        NOT NULL REFERENCES products (id),
    batch_id      BIGINT REFERENCES stock_batches (id),
    batch_no      VARCHAR(40),
    expiry_date   DATE,
    qty_change    NUMERIC(14,3) NOT NULL CHECK (qty_change <> 0),
    unit_cost     NUMERIC(14,4) NOT NULL DEFAULT 0
);

CREATE TABLE stock_transfers (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id       BIGINT       NOT NULL REFERENCES businesses (id),
    number            VARCHAR(30)  NOT NULL,
    kind              VARCHAR(10)  NOT NULL CHECK (kind IN ('MOVE', 'BRANCH')),
    from_warehouse_id BIGINT       NOT NULL REFERENCES warehouses (id),
    to_warehouse_id   BIGINT       NOT NULL REFERENCES warehouses (id),
    status            VARCHAR(12)  NOT NULL CHECK (status IN ('DRAFT', 'MOVED', 'IN_TRANSIT', 'RECEIVED', 'RETURNED', 'VOID')),
    sent_at           TIMESTAMPTZ,
    sent_by           BIGINT,
    received_at       TIMESTAMPTZ,
    received_by       BIGINT,
    returned_at       TIMESTAMPTZ,
    returned_by       BIGINT,
    return_reason     VARCHAR(255),
    carrier_note      VARCHAR(255),
    adjustment_id     BIGINT REFERENCES stock_adjustments (id),
    note              VARCHAR(500),
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by        BIGINT,
    updated_by        BIGINT,
    UNIQUE (business_id, number),
    CHECK (from_warehouse_id <> to_warehouse_id)
);

CREATE TABLE stock_transfer_items (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id  BIGINT        NOT NULL REFERENCES businesses (id),
    transfer_id  BIGINT        NOT NULL REFERENCES stock_transfers (id) ON DELETE CASCADE,
    product_id   BIGINT        NOT NULL REFERENCES products (id),
    unit_id      BIGINT        NOT NULL REFERENCES units (id),
    qty          NUMERIC(14,3) NOT NULL CHECK (qty > 0),
    base_qty     NUMERIC(14,3) NOT NULL CHECK (base_qty > 0),
    batch_id     BIGINT REFERENCES stock_batches (id),
    batch_no     VARCHAR(40),
    expiry_date  DATE,
    qty_received NUMERIC(14,3),
    unit_cost    NUMERIC(14,4)
);

-- ---------------------------------------------------------------- purchases

CREATE TABLE purchase_orders (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id          BIGINT        NOT NULL REFERENCES businesses (id),
    number               VARCHAR(30)   NOT NULL,
    supplier_id          BIGINT        NOT NULL REFERENCES suppliers (id),
    branch_id            BIGINT        NOT NULL REFERENCES branches (id),
    receive_warehouse_id BIGINT        NOT NULL REFERENCES warehouses (id),
    order_date           DATE          NOT NULL,
    expected_date        DATE,
    currency             VARCHAR(3)    NOT NULL DEFAULT 'USD',
    exchange_rate        NUMERIC(10,2) NOT NULL,
    subtotal             NUMERIC(14,2) NOT NULL DEFAULT 0,
    discount             NUMERIC(14,2) NOT NULL DEFAULT 0,
    vat                  NUMERIC(14,2) NOT NULL DEFAULT 0,
    total                NUMERIC(14,2) NOT NULL DEFAULT 0,
    status               VARCHAR(20)   NOT NULL CHECK (status IN ('DRAFT', 'ORDERED', 'PARTIALLY_RECEIVED', 'RECEIVED',
                                                                  'CLOSED', 'CANCELLED')),
    note                 VARCHAR(500),
    created_at           TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at           TIMESTAMPTZ   NOT NULL DEFAULT now(),
    created_by           BIGINT,
    updated_by           BIGINT,
    UNIQUE (business_id, number)
);

CREATE TABLE purchase_order_items (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id       BIGINT        NOT NULL REFERENCES businesses (id),
    purchase_order_id BIGINT        NOT NULL REFERENCES purchase_orders (id) ON DELETE CASCADE,
    product_id        BIGINT        NOT NULL REFERENCES products (id),
    unit_id           BIGINT        NOT NULL REFERENCES units (id),
    qty_ordered       NUMERIC(14,3) NOT NULL CHECK (qty_ordered > 0),
    qty_received      NUMERIC(14,3) NOT NULL DEFAULT 0,
    unit_cost         NUMERIC(14,4) NOT NULL CHECK (unit_cost >= 0)
);

CREATE TABLE goods_receipts (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id       BIGINT       NOT NULL REFERENCES businesses (id),
    number            VARCHAR(30)  NOT NULL,
    purchase_order_id BIGINT       NOT NULL REFERENCES purchase_orders (id),
    branch_id         BIGINT       NOT NULL REFERENCES branches (id),
    warehouse_id      BIGINT       NOT NULL REFERENCES warehouses (id),
