    base_qty         NUMERIC(14,3) NOT NULL,
    unit_price       NUMERIC(14,2) NOT NULL,
    discount         NUMERIC(14,2) NOT NULL DEFAULT 0,
    cost_at_sale     NUMERIC(14,4) NOT NULL,
    CHECK ((sales_receipt_id IS NULL) <> (delivery_id IS NULL))
);

