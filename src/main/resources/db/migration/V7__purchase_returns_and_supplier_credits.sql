-- Purchase returns and supplier credits (FR-2.7, FR-2.8, PLAIN.md 11.7). A return is made from a goods receipt, so the
-- batch and the price are known: the goods leave stock and a supplier credit is made for their value, used on a bill
-- or refunded by the supplier. Supplier credits can also be made by hand for a price correction.

CREATE TABLE purchase_returns (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id      BIGINT        NOT NULL REFERENCES businesses (id),
    number           VARCHAR(30)   NOT NULL,
    branch_id        BIGINT        NOT NULL REFERENCES branches (id),
    warehouse_id     BIGINT        NOT NULL REFERENCES warehouses (id),
    supplier_id      BIGINT        NOT NULL REFERENCES suppliers (id),
    goods_receipt_id BIGINT        NOT NULL REFERENCES goods_receipts (id),
    returned_at      TIMESTAMPTZ   NOT NULL,
    total            NUMERIC(14,2) NOT NULL,
    reason           VARCHAR(255),
    status           VARCHAR(10)   NOT NULL CHECK (status IN ('POSTED', 'VOID')),
    created_at       TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ   NOT NULL DEFAULT now(),
    created_by       BIGINT,
    updated_by       BIGINT,
    UNIQUE (business_id, number)
);
CREATE INDEX purchase_returns_receipt ON purchase_returns (business_id, goods_receipt_id);

CREATE TABLE purchase_return_items (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id           BIGINT        NOT NULL REFERENCES businesses (id),
    return_id             BIGINT        NOT NULL REFERENCES purchase_returns (id) ON DELETE CASCADE,
    goods_receipt_item_id BIGINT        NOT NULL REFERENCES goods_receipt_items (id),
    product_id            BIGINT        NOT NULL REFERENCES products (id),
    unit_id               BIGINT        NOT NULL REFERENCES units (id),
    qty                   NUMERIC(14,3) NOT NULL CHECK (qty > 0),
    base_qty              NUMERIC(14,3) NOT NULL CHECK (base_qty > 0),
    -- the cost of one unit_id as received, and qty x unit_cost
    unit_cost             NUMERIC(14,4) NOT NULL,
    amount                NUMERIC(14,2) NOT NULL,
    batch_no              VARCHAR(40),
    expiry_date           DATE
);
CREATE INDEX purchase_return_items_receipt_item ON purchase_return_items (goods_receipt_item_id);

CREATE TABLE supplier_credits (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id        BIGINT        NOT NULL REFERENCES businesses (id),
    number             VARCHAR(30)   NOT NULL,
    branch_id          BIGINT        NOT NULL REFERENCES branches (id),
    supplier_id        BIGINT        NOT NULL REFERENCES suppliers (id),
    purchase_return_id BIGINT REFERENCES purchase_returns (id),
    issued_at          TIMESTAMPTZ   NOT NULL,
    amount             NUMERIC(14,2) NOT NULL CHECK (amount > 0),
    used_amount        NUMERIC(14,2) NOT NULL DEFAULT 0,
    refunded_amount    NUMERIC(14,2) NOT NULL DEFAULT 0,
    status             VARCHAR(10)   NOT NULL CHECK (status IN ('OPEN', 'CLOSED', 'VOID')),
    reason             VARCHAR(255),
    created_at         TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ   NOT NULL DEFAULT now(),
    created_by         BIGINT,
    updated_by         BIGINT,
    UNIQUE (business_id, number),
    CHECK (used_amount + refunded_amount <= amount)
);
CREATE INDEX supplier_credits_supplier ON supplier_credits (business_id, supplier_id, status);

