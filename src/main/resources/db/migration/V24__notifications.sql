-- In-app notifications (PLAIN.md 10.2, 11.10: "In-app notifications go to each member according to their role"): one row
-- per member for something that happened (a transfer on its way to their branch, a document waiting for their
-- approval, a cash shift closed short, a sale voided, a product out of stock). The text is made in the member's language
-- from type + params; link opens the page that deals with it. Read ones older than 90 days are removed.
CREATE TABLE notifications (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT       NOT NULL REFERENCES businesses (id),
    user_id     BIGINT       NOT NULL REFERENCES users (id),
    type        VARCHAR(40)  NOT NULL,
    params      TEXT         NOT NULL DEFAULT '{}',
    link        VARCHAR(255),
    read_at     TIMESTAMPTZ,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX notifications_user ON notifications (business_id, user_id, created_at DESC);
