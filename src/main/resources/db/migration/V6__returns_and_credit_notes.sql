-- Sales returns and credit notes (FR-3.12, PLAIN.md 11.8). A return comes from a sales receipt or an invoice: good
-- items go back to stock, damaged ones are a loss. Each return makes a credit note for its value, used on invoices or
-- refunded; credit notes can also be made by hand for a price correction.

CREATE TABLE sales_returns (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id      BIGINT        NOT NULL REFERENCES businesses (id),
    number           VARCHAR(30)   NOT NULL,
    branch_id        BIGINT        NOT NULL REFERENCES branches (id),
    warehouse_id     BIGINT        NOT NULL REFERENCES warehouses (id),
    customer_id      BIGINT REFERENCES customers (id),
    sales_receipt_id BIGINT REFERENCES sales_receipts (id),
    invoice_id       BIGINT REFERENCES invoices (id),
    returned_at      TIMESTAMPTZ   NOT NULL,
    vat              NUMERIC(14,2) NOT NULL DEFAULT 0,
    total            NUMERIC(14,2) NOT NULL,
    loss_value       NUMERIC(14,2) NOT NULL DEFAULT 0,
    reason           VARCHAR(255),
    status           VARCHAR(10)   NOT NULL CHECK (status IN ('POSTED', 'VOID')),
    created_at       TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ   NOT NULL DEFAULT now(),
    created_by       BIGINT,
    updated_by       BIGINT,
    UNIQUE (business_id, number),
    CHECK ((sales_receipt_id IS NULL) <> (invoice_id IS NULL))
);

CREATE TABLE sales_return_items (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id   BIGINT        NOT NULL REFERENCES businesses (id),
    return_id     BIGINT        NOT NULL REFERENCES sales_returns (id) ON DELETE CASCADE,
    sale_item_id  BIGINT        NOT NULL REFERENCES sale_items (id),
    product_id    BIGINT        NOT NULL REFERENCES products (id),
    unit_id       BIGINT        NOT NULL REFERENCES units (id),
    qty           NUMERIC(14,3) NOT NULL CHECK (qty > 0),
    base_qty      NUMERIC(14,3) NOT NULL CHECK (base_qty > 0),
    -- the line's price per unit after its discount, and the money given back for this line (its share of the sale)
    unit_net      NUMERIC(14,4) NOT NULL,
    refund        NUMERIC(14,2) NOT NULL,
    cost_at_sale  NUMERIC(14,4) NOT NULL,
    condition     VARCHAR(8)    NOT NULL CHECK (condition IN ('GOOD', 'DAMAGED')),
    batch_no      VARCHAR(40),
    expiry_date   DATE
);
CREATE INDEX sales_return_items_sale_item ON sales_return_items (sale_item_id);

CREATE TABLE credit_notes (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id     BIGINT        NOT NULL REFERENCES businesses (id),
    number          VARCHAR(30)   NOT NULL,
    branch_id       BIGINT        NOT NULL REFERENCES branches (id),
    customer_id     BIGINT REFERENCES customers (id),
    sales_return_id BIGINT REFERENCES sales_returns (id),
    issued_at       TIMESTAMPTZ   NOT NULL,
    amount          NUMERIC(14,2) NOT NULL CHECK (amount > 0),
    used_amount     NUMERIC(14,2) NOT NULL DEFAULT 0,
    refunded_amount NUMERIC(14,2) NOT NULL DEFAULT 0,
    status          VARCHAR(10)   NOT NULL CHECK (status IN ('OPEN', 'CLOSED', 'VOID')),
    reason          VARCHAR(255),
    created_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    created_by      BIGINT,
    updated_by      BIGINT,
    UNIQUE (business_id, number),
    CHECK (used_amount + refunded_amount <= amount)
);
