-- Coupons (FR-10.16): the super admin makes them; an Owner enters one on the Billing page and the next full-period
-- invoices (first and renewals) get the discount.
CREATE TABLE coupons (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            VARCHAR(30)  NOT NULL UNIQUE,
    percent_off     INT          NOT NULL CHECK (percent_off BETWEEN 1 AND 100),
    periods         INT          NOT NULL CHECK (periods BETWEEN 1 AND 24),
    max_redemptions INT          CHECK (max_redemptions > 0),
    expires_on      DATE,
    is_active       BOOLEAN      NOT NULL DEFAULT TRUE,
    note            VARCHAR(255),
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE coupon_redemptions (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    coupon_id    BIGINT       NOT NULL REFERENCES coupons (id),
    business_id  BIGINT       NOT NULL REFERENCES businesses (id),
    periods_left INT          NOT NULL CHECK (periods_left >= 0),
    redeemed_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    UNIQUE (coupon_id, business_id)
);

ALTER TABLE billing_invoices ADD COLUMN discount NUMERIC(14,2) NOT NULL DEFAULT 0;
ALTER TABLE billing_invoices ADD COLUMN coupon_code VARCHAR(30);
