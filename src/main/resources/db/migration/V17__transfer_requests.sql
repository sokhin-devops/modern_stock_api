-- Transfer requests (FR-4.11): a branch asks another for goods; the other branch makes the transfer, or declines.
CREATE TABLE stock_requests (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id    BIGINT       NOT NULL REFERENCES businesses (id),
    number         VARCHAR(30)  NOT NULL,
    from_branch_id BIGINT       NOT NULL REFERENCES branches (id),
    to_branch_id   BIGINT       NOT NULL REFERENCES branches (id),
    status         VARCHAR(12)  NOT NULL CHECK (status IN ('OPEN', 'FULFILLED', 'DECLINED', 'CANCELLED')),
    needed_by      DATE,
    note           VARCHAR(500),
    requested_by   BIGINT       REFERENCES users (id),
    decided_by     BIGINT       REFERENCES users (id),
    decided_at     TIMESTAMPTZ,
    decline_reason VARCHAR(255),
    transfer_id    BIGINT       REFERENCES stock_transfers (id),
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by     BIGINT,
    updated_by     BIGINT,
    UNIQUE (business_id, number),
    CHECK (from_branch_id <> to_branch_id)
);
CREATE INDEX ix_stock_requests_status ON stock_requests (business_id, status);

CREATE TABLE stock_request_items (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT        NOT NULL REFERENCES businesses (id),
    request_id  BIGINT        NOT NULL REFERENCES stock_requests (id) ON DELETE CASCADE,
    product_id  BIGINT        NOT NULL REFERENCES products (id),
    unit_id     BIGINT        NOT NULL REFERENCES units (id),
    qty         NUMERIC(14,3) NOT NULL CHECK (qty > 0),
    base_qty    NUMERIC(14,3) NOT NULL CHECK (base_qty > 0)
);
